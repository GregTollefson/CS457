-- Upgrade existing databases without changing existing series or observations.
-- Run once after reviewing; the transaction makes the upgrade atomic.
BEGIN;

CREATE TABLE category (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code TEXT NOT NULL UNIQUE,
    category_name TEXT NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE metric (
    metric_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_code TEXT NOT NULL UNIQUE,
    metric_name TEXT NOT NULL,
    category_id INTEGER NOT NULL REFERENCES category(category_id),
    description TEXT
);

CREATE TABLE source (
    source_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name TEXT NOT NULL UNIQUE,
    description TEXT
);

ALTER TABLE series
    ADD COLUMN metric_id INTEGER REFERENCES metric(metric_id),
    ADD COLUMN source_id INTEGER REFERENCES source(source_id);

COMMIT;
