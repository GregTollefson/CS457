
-- Complete current schema for a clean installation.
-- Existing databases must use sql/migrations/ instead.
--
-- Research database for electricity prices, utility capacity,
-- capacity utilization, and infrastructure investment.
-- Data is retrieved from the Federal Reserve Economic Data (FRED) API.


-- ============================================================
-- CATEGORY
-- Broad research grouping for economic indicators.
--
-- Examples:
--   Price
--   Capacity
--   Investment
--
-- Categories are defined by our research model, not downloaded
-- directly from FRED. Each category can contain multiple metrics.
-- ============================================================

CREATE TABLE IF NOT EXISTS category (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code TEXT NOT NULL UNIQUE,
    category_name TEXT NOT NULL UNIQUE,
    description TEXT
);


-- ============================================================
-- METRIC
-- Specific economic measurement within a research category.
--
-- Examples:
--   Electricity Price
--   Utility Capacity
--   Capacity Utilization
--   Power Construction
--
-- Metrics are defined locally to organize related FRED series.
-- Each metric belongs to one category, while a metric may
-- correspond to multiple FRED series.
-- ============================================================

CREATE TABLE IF NOT EXISTS metric (
    metric_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_code TEXT NOT NULL UNIQUE,
    metric_name TEXT NOT NULL,
    category_id INTEGER NOT NULL REFERENCES category(category_id),
    description TEXT
);


-- ============================================================
-- SOURCE
-- Identifies the external provider of economic data.
--
-- Example:
--   FRED (Federal Reserve Economic Data)
--
-- Allows multiple sources to be incorporated into the
-- research database without changing the table structure.
-- ============================================================

CREATE TABLE IF NOT EXISTS source (
    source_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name TEXT NOT NULL UNIQUE,
    description TEXT
);


-- ============================================================
-- SERIES
-- Metadata describing each time series retrieved from FRED.
--
-- Examples:
--   APU000072610  - Electricity price
--   CAPG2211S     - Utility capacity
--   CAPUTLG2211S  - Capacity utilization
--
-- Stores descriptive information returned by the FRED API,
-- including title, frequency, units, seasonal adjustment,
-- observation date range, update timestamp, and popularity.
--
-- metric_id connects the series to our research classification.
-- source_id identifies the external data provider.
-- ============================================================

CREATE TABLE IF NOT EXISTS series (
    series_id VARCHAR(50) PRIMARY KEY,
    title TEXT NOT NULL,
    frequency VARCHAR(50),
    units VARCHAR(100),
    seasonal_adjustment VARCHAR(100),
    observation_start DATE,
    observation_end DATE,
    last_updated TIMESTAMPTZ,
    popularity INTEGER,
    notes TEXT,
    metric_id INTEGER REFERENCES metric(metric_id),
    source_id INTEGER REFERENCES source(source_id)
);


-- ============================================================
-- OBSERVATIONS
-- Individual time-series data points retrieved from FRED.
--
-- Each row represents the observed value of a specific
-- economic series on a particular date.
--
-- Example:
--   series_id       date          value
--   APU000072610    2024-01-01    0.175
--
-- The composite primary key (series_id, date) prevents
-- duplicate observations for the same series and date.
--
-- NULL values are permitted because FRED may report
-- missing observations.
--
-- realtime_start and realtime_end store FRED's real-time
-- validity dates when provided by the ingestion process.
--
-- ON DELETE CASCADE removes observations automatically
-- when their parent series is deleted.
-- ============================================================

CREATE TABLE IF NOT EXISTS observations (
    series_id VARCHAR(50) NOT NULL,
    date DATE NOT NULL,
    value DOUBLE PRECISION,
    realtime_start DATE,
    realtime_end DATE,

    PRIMARY KEY (series_id, date),

    FOREIGN KEY (series_id)
        REFERENCES series(series_id)
        ON DELETE CASCADE
);
