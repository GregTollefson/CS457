-- Complete current schema for a clean installation.
-- Existing databases must use sql/migrations/ instead.

CREATE TABLE IF NOT EXISTS category (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code TEXT NOT NULL UNIQUE,
    category_name TEXT NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS metric (
    metric_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_code TEXT NOT NULL UNIQUE,
    metric_name TEXT NOT NULL,
    category_id INTEGER NOT NULL REFERENCES category(category_id),
    description TEXT
);

CREATE TABLE IF NOT EXISTS source (
    source_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name TEXT NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS series (
    series_id VARCHAR(50) PRIMARY KEY,
    title TEXT NOT NULL,
    frequency VARCHAR(50),
    units VARCHAR(100),
    seasonal_adjustment VARCHAR(100),
    observation_start DATE,
    observation_end DATE,
    last_updated TIMESTAMPTZ,
    popularity INTEGER,
    notes TEXT,
    metric_id INTEGER REFERENCES metric(metric_id),
    source_id INTEGER REFERENCES source(source_id)
);

CREATE TABLE IF NOT EXISTS observations (
    series_id VARCHAR(50) NOT NULL,
    date DATE NOT NULL,
    value DOUBLE PRECISION,
    realtime_start DATE,
    realtime_end DATE,

    PRIMARY KEY (series_id, date),

    FOREIGN KEY (series_id)
        REFERENCES series(series_id)
        ON DELETE CASCADE
);
